#!/usr/bin/env python3
"""
ATOMICA Task Coordinator & File Lock Manager (Fallen Leaf System)
Enforces exclusive task claiming, file locking, and concurrency prevention
between Claude and Gemini.

Specification: Section 22 of ATOMICA Charter.
"""

import os
import sys
import json
import time
import argparse
from datetime import datetime, timezone
from pathlib import Path

# Base Paths
REPO_ROOT = Path(__file__).resolve().parent.parent
TASK_SYS_DIR = REPO_ROOT / "project-management" / "task-system"
LOCKS_FILE = TASK_SYS_DIR / "locks.json"
OWNERSHIP_FILE = TASK_SYS_DIR / "FILE_OWNERSHIP.md"
TASK_BOARD_FILE = TASK_SYS_DIR / "TASK_BOARD.md"
LOCK_HISTORY_FILE = TASK_SYS_DIR / "LOCK_HISTORY.md"
AGENT_REGISTRY_FILE = TASK_SYS_DIR / "AGENT_REGISTRY.md"

VALID_AGENTS = ["claude", "gemini", "coordinator"]
VALID_STATUSES = [
    "BACKLOG", "READY", "CLAIMED", "IN_PROGRESS", "BLOCKED",
    "WAITING_FOR_LOCK", "REVIEW", "NEEDS_REVISION", "INTEGRATING",
    "TESTING", "COMPLETE", "CANCELLED"
]


def normalize_path(path_str: str) -> str:
    """Normalize file or directory paths to forward slash relative to repo root."""
    p = Path(path_str.strip())
    if p.is_absolute():
        try:
            p = p.relative_to(REPO_ROOT)
        except ValueError:
            pass
    norm = str(p).replace("\\", "/")
    if norm.startswith("./"):
        norm = norm[2:]
    return norm


def load_locks() -> dict:
    if not LOCKS_FILE.exists():
        return {"version": "1.0.0", "locks": {}, "tasks": {}}
    try:
        with open(LOCKS_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception as e:
        sys.stderr.write(f"Error loading {LOCKS_FILE}: {e}\n")
        return {"version": "1.0.0", "locks": {}, "tasks": {}}


def save_locks(data: dict):
    TASK_SYS_DIR.mkdir(parents=True, exist_ok=True)
    temp_file = TASK_SYS_DIR / f"locks_{os.getpid()}_{int(time.time()*1000)}.tmp"
    with open(temp_file, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)
    os.replace(temp_file, LOCKS_FILE)


def paths_conflict(path1: str, path2: str) -> bool:
    """Check if two path reservations conflict (exact match or parent/child directory)."""
    p1 = path1.rstrip("/")
    p2 = path2.rstrip("/")
    if p1 == p2:
        return True
    # If p1 is directory and p2 is inside p1
    if p2.startswith(p1 + "/"):
        return True
    # If p2 is directory and p1 is inside p2
    if p1.startswith(p2 + "/"):
        return True
    return False


def update_markdown_ownership(locks_data: dict):
    """Regenerate FILE_OWNERSHIP.md based on active locks."""
    lines = [
        "# ATOMICA: Active File Ownership & Lock Registry",
        "",
        "> **Auto-generated by Fallen Leaf Task Coordinator (`scripts/coordinator.py`).**",
        f"> **Last Updated:** {datetime.now(timezone.utc).isoformat()}",
        "",
        "| File / Directory Scope | Owning Agent | Task ID | Acquired At | Expires At | Status |",
        "| :--- | :---: | :---: | :--- | :--- | :---: |"
    ]
    
    active_locks = locks_data.get("locks", {})
    if not active_locks:
        lines.append("| *(No active locks)* | - | - | - | - | `IDLE` |")
    else:
        for path, info in sorted(active_locks.items()):
            lines.append(
                f"| `{path}` | `agent/{info['agent']}` | `{info['taskId']}` | "
                f"{info['acquiredAt']} | {info.get('expiresAt', 'Permanent')} | `LOCKED` |"
            )
            
    lines.extend([
        "",
        "---",
        "## Ownership Enforcement Rule",
        "Per Section 22: **Claude and Gemini must NEVER modify the same files simultaneously.**",
        "Before modifying any file, an agent must acquire a lock via `python scripts/coordinator.py claim --agent <name> --task <id> --files <path>`."
    ])
    
    with open(OWNERSHIP_FILE, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def append_lock_history(action: str, agent: str, task_id: str, files: list, details: str = ""):
    """Append audit trail event to LOCK_HISTORY.md."""
    TASK_SYS_DIR.mkdir(parents=True, exist_ok=True)
    if not LOCK_HISTORY_FILE.exists():
        header = [
            "# ATOMICA: Task & File Lock Audit History",
            "",
            "| Timestamp (UTC) | Action | Agent | Task ID | Files / Scope | Details |",
            "| :--- | :---: | :---: | :---: | :--- | :--- |"
        ]
        with open(LOCK_HISTORY_FILE, "w", encoding="utf-8") as f:
            f.write("\n".join(header) + "\n")
            
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")
    files_str = "<br>".join([f"`{f}`" for f in files]) if files else "-"
    entry = f"| {now} | `{action}` | `agent/{agent}` | `{task_id}` | {files_str} | {details} |\n"
    with open(LOCK_HISTORY_FILE, "a", encoding="utf-8") as f:
        f.write(entry)


def cmd_claim(args):
    agent = args.agent.lower().replace("agent/", "")
    if agent not in VALID_AGENTS:
        sys.stderr.write(f"ERROR: Unknown agent '{agent}'. Must be one of: {VALID_AGENTS}\n")
        sys.exit(1)

    task_id = args.task.upper()
    files = [normalize_path(f) for f in args.files]
    if not files:
        sys.stderr.write("ERROR: Must specify at least one file or directory to reserve with --files\n")
        sys.exit(1)

    locks_data = load_locks()
    active_locks = locks_data.get("locks", {})
    active_tasks = locks_data.get("tasks", {})

    # Check for file conflicts
    conflicts = []
    for req_file in files:
        for locked_path, lock_info in active_locks.items():
            if paths_conflict(req_file, locked_path):
                if lock_info["agent"] != agent or lock_info["taskId"] != task_id:
                    conflicts.append({
                        "requested": req_file,
                        "locked": locked_path,
                        "heldBy": lock_info["agent"],
                        "taskId": lock_info["taskId"]
                    })

    if conflicts:
        print(f"\n[REJECTED] Task claim denied for {task_id} by agent/{agent}:")
        print("Conflicting file locks currently held by another agent:")
        for c in conflicts:
            print(f"  - Requested: `{c['requested']}` conflicts with `{c['locked']}` "
                  f"(Held by `agent/{c['heldBy']}` on task `{c['taskId']}`)")
        print("\nACTION REQUIRED: Wait for lock release, or claim non-overlapping files.\n")
        sys.exit(2)

    # Grant locks
    now_iso = datetime.now(timezone.utc).isoformat()
    duration_hours = args.hours if args.hours else 12
    expires_ts = time.time() + (duration_hours * 3600)
    expires_iso = datetime.fromtimestamp(expires_ts, tz=timezone.utc).isoformat()

    for f in files:
        active_locks[f] = {
            "agent": agent,
            "taskId": task_id,
            "acquiredAt": now_iso,
            "expiresAt": expires_iso
        }

    active_tasks[task_id] = {
        "agent": agent,
        "status": "IN_PROGRESS",
        "files": files,
        "claimedAt": now_iso
    }

    locks_data["locks"] = active_locks
    locks_data["tasks"] = active_tasks
    save_locks(locks_data)
    update_markdown_ownership(locks_data)
    append_lock_history("CLAIM", agent, task_id, files, f"Granted {duration_hours}h lock lease.")

    print(f"\n[GRANTED] Task {task_id} successfully claimed by agent/{agent}!")
    print(f"Active file reservations ({len(files)} files):")
    for f in files:
        print(f"  + [LOCKED] {f}")
    print(f"Lease expires: {expires_iso}\n")


def cmd_release(args):
    agent = args.agent.lower().replace("agent/", "")
    task_id = args.task.upper()
    summary = args.summary or "Task work completed or released."

    locks_data = load_locks()
    active_locks = locks_data.get("locks", {})
    active_tasks = locks_data.get("tasks", {})

    # Find locks for this task
    released_files = []
    to_delete = []
    for path, info in active_locks.items():
        if info["taskId"] == task_id:
            if info["agent"] != agent and agent != "coordinator":
                sys.stderr.write(f"ERROR: Cannot release locks owned by agent/{info['agent']}!\n")
                sys.exit(1)
            released_files.append(path)
            to_delete.append(path)

    for p in to_delete:
        del active_locks[p]

    if task_id in active_tasks:
        active_tasks[task_id]["status"] = args.status or "COMPLETE"
        active_tasks[task_id]["releasedAt"] = datetime.now(timezone.utc).isoformat()

    locks_data["locks"] = active_locks
    locks_data["tasks"] = active_tasks
    save_locks(locks_data)
    update_markdown_ownership(locks_data)
    append_lock_history("RELEASE", agent, task_id, released_files, summary)

    print(f"\n[RELEASED] Task {task_id} file locks released by agent/{agent}.")
    print(f"Freed {len(released_files)} file reservations:")
    for f in released_files:
        print(f"  - [UNLOCKED] {f}")
    print()


def cmd_check(args):
    target = normalize_path(args.file)
    locks_data = load_locks()
    active_locks = locks_data.get("locks", {})

    found_locks = []
    for path, info in active_locks.items():
        if paths_conflict(target, path):
            found_locks.append((path, info))

    if found_locks:
        print(f"\n[LOCKED] File '{target}' is currently reserved:")
        for path, info in found_locks:
            print(f"  Scope: `{path}` | Owned by: `agent/{info['agent']}` | Task: `{info['taskId']}` | Expires: {info['expiresAt']}")
        print()
    else:
        print(f"\n[AVAILABLE] File '{target}' is free to claim.\n")


def cmd_list(args):
    locks_data = load_locks()
    active_locks = locks_data.get("locks", {})
    print(f"\n--- ATOMICA ACTIVE FILE LOCKS ({len(active_locks)}) ---")
    if not active_locks:
        print("  (No active file reservations)\n")
        return
    for path, info in sorted(active_locks.items()):
        print(f"  [{info['agent'].upper()}] `{path}` (Task: {info['taskId']}, Expires: {info['expiresAt']})")
    print()


def cmd_status(args):
    locks_data = load_locks()
    active_locks = locks_data.get("locks", {})
    active_tasks = locks_data.get("tasks", {})
    print(f"\n=== ATOMICA FALLEN LEAF TASK COORDINATOR STATUS ===")
    print(f"Active Tasks: {len(active_tasks)}")
    for tid, tinfo in active_tasks.items():
        print(f"  - {tid}: agent/{tinfo['agent']} [{tinfo['status']}] ({len(tinfo.get('files', []))} files)")
    print(f"\nTotal Active File Locks: {len(active_locks)}")
    cmd_list(args)


def main():
    parser = argparse.ArgumentParser(description="ATOMICA Fallen Leaf Multi-Agent Task & File Lock Coordinator")
    subparsers = parser.add_subparsers(dest="command", required=True)

    # Claim
    claim_p = subparsers.add_parser("claim", help="Exclusively claim a task and lock required files")
    claim_p.add_argument("--agent", required=True, help="Agent claiming task (claude / gemini)")
    claim_p.add_argument("--task", required=True, help="Task ID (e.g. TSK-001)")
    claim_p.add_argument("--files", nargs="+", required=True, help="Files or directory scopes to lock")
    claim_p.add_argument("--hours", type=float, default=12.0, help="Lock lease duration in hours")
    claim_p.set_defaults(func=cmd_claim)

    # Release
    rel_p = subparsers.add_parser("release", help="Release task file locks upon completion")
    rel_p.add_argument("--agent", required=True, help="Agent releasing task (claude / gemini)")
    rel_p.add_argument("--task", required=True, help="Task ID to release")
    rel_p.add_argument("--status", default="COMPLETE", choices=VALID_STATUSES, help="Final task status")
    rel_p.add_argument("--summary", default="", help="Handoff or completion summary")
    rel_p.set_defaults(func=cmd_release)

    # Check
    check_p = subparsers.add_parser("check", help="Check if a specific file is locked")
    check_p.add_argument("--file", required=True, help="File path to check")
    check_p.set_defaults(func=cmd_check)

    # List
    list_p = subparsers.add_parser("list-locks", help="List all currently active file locks")
    list_p.set_defaults(func=cmd_list)

    # Status
    status_p = subparsers.add_parser("status", help="Show full task and lock status")
    status_p.set_defaults(func=cmd_status)

    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
